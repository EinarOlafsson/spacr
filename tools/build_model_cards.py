"""Write one GitHub-rendered Markdown card per published spaCR model.

The cards live in ``docs/models/<key>.md`` with an index at
``docs/models/README.md``; each opens with readable score text, then its SVG,
``docs/models/cards/<key>.svg``, drawn by ``tools/build_score_cards.py``.
Every field and number on a card is read from ``BUNDLED_REMOTE_MODELS`` in
``spacr/model_zoo.py``, the same records the Model Zoo screen and the
website's model cards are built from. The scores come from the model's
3-page card data (``spacr/resources/model_cards``, the ground-truth re-score
of 2026-10-11) where one exists, so a re-score reaches the cards by
re-running this tool.

A family is a zoo key without its ``_vN`` suffix. Its default is the newest
version that is neither an alternative nor a candidate, the same rule the
website's Models tab uses. Alpha models are left out, as they are in the
README.

Run it::

    python tools/build_model_cards.py           # rewrite docs/models
    python tools/build_model_cards.py --check   # exit 1 if a card is stale
"""
from __future__ import annotations

import argparse
import importlib.util
import re
import sys
from pathlib import Path
from typing import Any, Dict, List, Mapping, Optional, Sequence, Tuple

ROOT = Path(__file__).resolve().parent.parent
CARD_DIR = ROOT / "docs" / "models"
INDEX_NAME = "README.md"
GENERATED_NOTE = ("<!-- Generated by tools/build_model_cards.py from "
                  "spacr/model_zoo.py; edit the zoo record, not this file. -->")

_VERSION_RE = re.compile(r"_v(\d+)$")
_SCORE_CARDS = None


def score_cards():
    """``tools/build_score_cards.py``, which draws the SVG score cards."""
    global _SCORE_CARDS
    if _SCORE_CARDS is None:
        path = Path(__file__).with_name("build_score_cards.py")
        spec = importlib.util.spec_from_file_location("spacr_score_cards",
                                                      path)
        module = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(module)
        _SCORE_CARDS = module
    return _SCORE_CARDS

METRIC_LABELS = {
    "f1": "F1",
    "boundary_f1_2px": "Boundary F1 (2 px)",
    "precision": "Precision",
    "recall": "Recall",
    "aji": "AJI",
    "dice": "Dice",
    "pixel_iou": "Pixel IoU",
    "mAP": "mAP",
    "ap": "AP",
    "mAP50": "mAP50",
    "mAP50_95": "mAP50-95",
    "true_positives": "True positives",
    "false_positives": "False positives",
    "false_negatives": "False negatives",
}

SUMMARY_LABELS = (
    ("n_train", "Training set"),
    ("train_objects", "Training objects"),
    ("n_test", "Test set"),
    ("test_objects", "Test objects"),
    ("cv", "Cross-validation"),
    ("f1", "F1"),
    ("aji", "AJI"),
    ("dice", "Dice"),
    ("stock_f1", "Stock F1"),
    ("stock_aji", "Stock AJI"),
    ("stock_dice", "Stock Dice"),
    ("train_loss", "Training loss"),
    ("val_loss", "Validation loss"),
    ("best_epoch", "Best epoch"),
)

_SCORE_FIELDS = ("f1", "aji", "dice")
_STOCK_FIELDS = {"stock_f1": "f1", "stock_aji": "aji", "stock_dice": "dice"}

STATUS_WORDS = {
    "default": "default",
    "alternative": "alternative",
    "candidate": "candidate",
    "older": "older version",
}


def published_models() -> List[Dict[str, Any]]:
    """The zoo records the README shows: every non-alpha bundled record."""
    sys.path.insert(0, str(ROOT))
    from spacr.model_zoo import BUNDLED_REMOTE_MODELS
    from spacr.settings import _is_alpha

    return [score_cards().rescored(entry) for entry in BUNDLED_REMOTE_MODELS
            if not _is_alpha("models",
                             str(entry.get("key") or entry.get("name") or ""))]


def key_of(entry: Mapping[str, Any]) -> str:
    """The zoo key of a record."""
    return str(entry.get("key") or entry.get("name") or "")


def family_and_version(key: str) -> Tuple[str, int]:
    """``toxoplasma_pv_v4`` -> ``("toxoplasma_pv", 4)``; no suffix is v1."""
    match = _VERSION_RE.search(key)
    if match:
        return key[:match.start()], int(match.group(1))
    return key, 1


def marker_of(entry: Mapping[str, Any]) -> str:
    """``alternative`` or ``candidate`` when the zoo marks the record so.

    Read from :mod:`spacr.model_zoo`, whose ``default_version_index`` skips
    the same two markers, so the cards, the README and the app's Model Zoo
    open a family on the same version.
    """
    sys.path.insert(0, str(ROOT))
    from spacr import model_zoo

    key = key_of(entry)
    if key in model_zoo.ALTERNATIVE_MODEL_KEYS:
        return "alternative"
    if key in model_zoo._CANDIDATE_MODEL_KEYS:
        return "candidate"
    return ""


def families(entries: Optional[Sequence[Mapping[str, Any]]] = None
             ) -> List[Dict[str, Any]]:
    """Model families in catalogue order, each with its default and the rest.

    :returns: dicts with ``stem``, ``default`` (a record), ``versions``
        (records, newest first) and ``status`` (key -> status word).
    """
    entries = published_models() if entries is None else list(entries)
    grouped: Dict[str, List[Mapping[str, Any]]] = {}
    for entry in entries:
        stem, _version = family_and_version(key_of(entry))
        grouped.setdefault(stem, []).append(entry)
    result = []
    for stem, members in grouped.items():
        versions = sorted(members, key=lambda e: family_and_version(key_of(e))[1],
                          reverse=True)
        from types import SimpleNamespace

        from spacr.model_zoo import default_version_index

        default = versions[default_version_index(
            [(key_of(e), SimpleNamespace(key=key_of(e))) for e in versions])]
        status = {}
        for entry in versions:
            if entry is default:
                status[key_of(entry)] = "default"
            else:
                status[key_of(entry)] = marker_of(entry) or "older"
        result.append({"stem": stem, "default": default,
                       "versions": versions, "status": status})
    return result


def default_records(entries=None) -> List[Mapping[str, Any]]:
    """The default version of every family, in catalogue order."""
    return [family["default"] for family in families(entries)]


def other_records(entries=None) -> List[Tuple[Mapping[str, Any], str]]:
    """Every non-default version as ``(record, status)``, family by family."""
    out = []
    for family in families(entries):
        for entry in family["versions"]:
            status = family["status"][key_of(entry)]
            if status != "default":
                out.append((entry, status))
    return out


def card_file(key: str) -> str:
    """The card's file name inside ``docs/models``."""
    return f"{key}.md"


def _cell(value: Any) -> str:
    return str(value).replace("|", "\\|").replace("\n", " ").strip()


def _sentence(text: str) -> str:
    text = str(text or "").strip()
    if text and text[-1] not in ".!?":
        text += "."
    first = text.split(" ", 1)[0]
    if first.isalpha() and first.islower():
        text = text[:1].upper() + text[1:]
    return text


def _number(value: Any) -> str:
    if value is None:
        return "not measured"
    if isinstance(value, bool):
        return str(value)
    if isinstance(value, float):
        return f"{value:.4f}"
    return str(value)


def _scorecard(metrics: Mapping[str, Any]) -> List[str]:
    rows = [(name, value) for name, value in metrics.items()
            if isinstance(value, dict) and value.get("finetuned") is not None]
    if not rows:
        return []
    with_stock = any(value.get("vanilla") is not None for _n, value in rows)
    header = "| Metric | This model |"
    rule = "| --- | --- |"
    if with_stock:
        header += " Stock | Difference |"
        rule += " --- | --- |"
    lines = [header, rule]
    for name, value in rows:
        line = f"| {METRIC_LABELS.get(name, name)} | {_number(value['finetuned'])} |"
        if with_stock:
            line += (f" {_number(value.get('vanilla'))} |"
                     f" {_number(value.get('delta'))} |")
        lines.append(line)
    lines.append("")
    holdout = metrics.get("holdout")
    if holdout:
        parts = [f"Evaluation set `{holdout}`"]
        if metrics.get("holdout_version"):
            parts[0] += f", version `{metrics['holdout_version']}`"
        counts = []
        if metrics.get("n_fields") not in (None, ""):
            counts.append(f"{metrics['n_fields']} scored fields")
        if metrics.get("n_objects") not in (None, ""):
            counts.append(f"{metrics['n_objects']} annotated objects")
        if counts:
            parts.append(" and ".join(counts))
        lines += ["; ".join(parts) + ".", ""]
    return lines


def _is_detector(entry: Mapping[str, Any]) -> bool:
    return (str(entry.get("kind") or "") == "detector"
            or "yolo" in str(entry.get("architecture") or "").lower())


def _summary(entry: Mapping[str, Any]) -> List[str]:
    metrics = entry.get("metrics") or {}
    structured = {name for name, value in metrics.items()
                  if isinstance(value, dict)}
    detector = _is_detector(entry)
    rows = []
    for field, label in SUMMARY_LABELS:
        value = metrics.get(field)
        if not isinstance(value, (str, int, float)) or isinstance(value, bool):
            continue
        text = str(value).strip()
        if (not text or text.lower() == "not measured"
                or text.lower().startswith(("not recorded",
                                            "not applicable"))):
            continue
        if field in _SCORE_FIELDS and structured:
            continue
        if field in _STOCK_FIELDS:
            twin = metrics.get(_STOCK_FIELDS[field])
            if isinstance(twin, dict) and twin.get("vanilla") is not None:
                continue
        if detector and field in _SCORE_FIELDS:
            label = "Scores"
        elif detector and field in _STOCK_FIELDS:
            label = "Baseline"
        if rows and rows[-1][0] == label and label in ("Scores", "Baseline"):
            rows[-1] = (label, f"{rows[-1][1]}; {text}")
            continue
        rows.append((label, text))
    if not rows:
        return []
    lines = ["| Recorded | Value |", "| --- | --- |"]
    lines += [f"| {label} | {_cell(text)} |" for label, text in rows]
    return lines + [""]


def _card_text(entry: Mapping[str, Any]) -> str:
    """Everything a card prints, for deciding which terms it explains."""
    metrics = entry.get("metrics") or {}
    bits = [str(entry.get("versus_stock") or "")]
    bits += [str(note) for note in entry.get("notes") or ()]
    bits += [f"{name} {value}" for name, value in metrics.items()]
    return " ".join(bits)


def _has_metric(metrics: Mapping[str, Any], name: str) -> bool:
    value = metrics.get(name)
    if isinstance(value, dict):
        return value.get("finetuned") is not None
    text = str(value or "").strip().lower()
    return bool(text) and not text.startswith(("not recorded", "not applicable",
                                               "not measured"))


def _cross_validated(entry: Mapping[str, Any]) -> bool:
    metrics = entry.get("metrics") or {}
    if re.match(r"\s*\d+-fold", str(metrics.get("cv") or "")):
        return True
    return bool(re.search(r"cross-validat", _card_text(entry), re.I))


def how_to_read(entry: Mapping[str, Any]) -> List[str]:
    """The "How to read these scores" bullets fitted to this card."""
    metrics = entry.get("metrics") or {}
    text = _card_text(entry)
    lines: List[str] = []
    if _is_detector(entry):
        lines.append(
            "**mAP50** is the mean average precision of the predicted boxes "
            "when a box counts as correct at an IoU of 0.5 or more with a "
            "reference box. **mAP50-95** averages it over ten IoU thresholds "
            "from 0.5 to 0.95, so loosely placed boxes score lower.")
        lines.append(
            "**IoU** (intersection over union) is the overlap between a "
            "predicted and a reference box divided by the area the two cover "
            "together.")
        if re.search(r"\bP\b|precision|recall|\bR\b", text, re.I):
            lines.append(
                "**Precision** (P) is the share of predicted boxes that match a "
                "reference box; low precision means false boxes. **Recall** (R) "
                "is the share of reference boxes the model found; low recall "
                "means missed wells.")
        if re.search(r"baseline|incumbent|\bv\d+\b", text):
            lines.append(
                "There is no stock model with a plaque-well class, so a "
                "detector is compared with an earlier spaCR detector scored on "
                "the same test images.")
    else:
        lines.append(
            "**Precision** is the share of objects the model reported that "
            "match a reference object; low precision means false detections. "
            "**Recall** is the share of reference objects the model found; "
            "low recall means missed objects.")
        lines.append(
            "**F1** is the harmonic mean of precision and recall, so it is "
            "high only when both are. Either alone can look near-perfect: a "
            "model that reports one obvious object has high precision, and "
            "one that reports every dark blob has high recall.")
        lines.append(
            "**IoU** (intersection over union) is the overlap between a "
            "predicted and a reference object divided by the area the two "
            "cover together. A score given at IoU 0.5 counts an object as "
            "found when that ratio reaches 0.5.")
        if _has_metric(metrics, "aji") or re.search(r"\bAJI\b", text):
            lines.append(
                "**AJI** (aggregated Jaccard index) adds up the overlap of "
                "every matched pair and divides it by their combined area plus "
                "the area of unmatched objects, so merged, split and missed "
                "objects all lower it.")
        if _has_metric(metrics, "dice") or re.search(r"\bDice\b", text):
            lines.append(
                "**Dice** is twice the overlap divided by the predicted area "
                "plus the reference area.")
        if _has_metric(metrics, "pixel_iou"):
            lines.append(
                "**Pixel IoU** is the IoU of all object pixels together, "
                "without matching objects one to one.")
        if (_has_metric(metrics, "ap") or _has_metric(metrics, "mAP")
                or re.search(r"\bm?AP\b", text)):
            lines.append(
                "**AP** at one IoU threshold is true positives divided by true "
                "positives, false positives and false negatives together. "
                "**mAP** averages it over IoU thresholds from 0.5 to 0.9, so "
                "it also rewards outlines that fit closely.")
        if re.search(r"\bstock\b", text, re.I):
            lines.append(
                "**Stock** is the base model named under Architecture, run "
                "without fine-tuning on the same images. **Difference** is "
                "this model's score minus stock's.")
    if _cross_validated(entry):
        lines.append(
            "**Cross-validated** scores split the data into folds, hold out "
            "each fold once and report the mean over folds with its standard "
            "deviation (**SD**, or +/-). A single split can mislead; the SD "
            "shows how far the score moves from one split to another.")
    hold_out = ("A **hold-out** or **test** set is images kept out of "
                "training and used only for scoring.")
    if re.search(r"re-scor", text, re.I):
        hold_out += (" The re-score note says how many of its fields this "
                     "model had not seen.")
    lines.append(hold_out)
    return [f"- {line}" for line in lines]


def _hf_url(entry: Mapping[str, Any]) -> str:
    repo = str(entry.get("repo_id") or "").strip()
    if not repo:
        return ""
    where = "datasets/" if str(entry.get("repo_type") or "model") == "dataset" else ""
    return f"https://huggingface.co/{where}{repo}"


def _link(entry: Mapping[str, Any], status: str = "") -> str:
    key = key_of(entry)
    text = f"[{key}]({card_file(key)})"
    if status and status not in ("default", "older"):
        text += f" ({STATUS_WORDS[status]})"
    return text


def render_card(entry: Mapping[str, Any], family: Mapping[str, Any]) -> str:
    """The Markdown card of one model."""
    key = key_of(entry)
    status = family["status"][key]
    title = str(entry.get("display_name") or key)
    scores = score_cards()
    lines = [GENERATED_NOTE, "", scores.readable_score(entry, status), ""]
    lines += [f"![{scores.alt_text(entry, status)}]"
              f"({scores.card_name(key)})", ""]
    lines += [f"## {title}", ""]
    head = f"`{key}`"
    architecture = str(entry.get("architecture") or "").strip()
    if architecture:
        head += f" · {architecture}"
    head += f" · {STATUS_WORDS[status]} in the `{family['stem']}` family"
    lines += [head, ""]
    segments, why = scores.segments_and_why(entry)
    if segments:
        lines += [f"{segments}. {why}".strip(), ""]
    default = family["default"]
    if status != "default":
        lines += [f"The family's default is {_link(default)}.", ""]
    others = [(e, family["status"][key_of(e)]) for e in family["versions"]
              if key_of(e) != key]
    if others:
        lines += ["Other versions: " + ", ".join(_link(e, s) for e, s in others)
                  + ".", ""]

    lines += ["## Training data", ""]
    dataset = str(entry.get("dataset") or "").strip()
    if dataset:
        lines += [_sentence(dataset), ""]
    trained_on = str(entry.get("trained_on") or "").strip()
    if trained_on:
        lines += [_sentence(trained_on), ""]

    lines += ["## Hold-out performance", ""]
    versus = str(entry.get("versus_stock") or "").strip()
    if versus:
        lines += [_sentence(versus), ""]
    metrics = entry.get("metrics") or {}
    lines += _scorecard(metrics)
    lines += _summary(entry)

    notes = [str(note).strip() for note in entry.get("notes") or ()
             if str(note).strip()]
    if notes:
        lines += ["## Notes", ""]
        lines += [f"- {_sentence(note)}" for note in notes]
        lines += [""]

    lines += ["## How to read these scores", ""]
    lines += how_to_read(entry)
    lines += [""]

    lines += ["## Files", ""]
    url = _hf_url(entry)
    if url:
        lines.append(f"- Hugging Face: [{entry['repo_id']}]({url})")
    elif entry.get("uri"):
        lines.append(f"- Download: <{entry['uri']}>")
    lines.append(f"- File name in spaCR: `{entry.get('name')}`")
    digest = str(entry.get("sha256") or "").strip()
    if digest:
        lines.append(f"- SHA-256: `{digest}`")
    if entry.get("trained_by"):
        lines.append(f"- Trained by: {entry['trained_by']}")
    if entry.get("licence"):
        lines.append(f"- Licence: {entry['licence']}")
    if entry.get("citation"):
        lines.append(f"- Citation: {entry['citation']}")
    lines += [
        "",
        "Models are hosted on each author's own Hugging Face account. "
        "spaCR downloads this one from there the first time it is needed and "
        "checks it against the SHA-256 above. "
        "`spacr.model_zoo.publish_model` uploads a model and returns the "
        "catalogue row to add.",
        "",
        f"[All model cards]({INDEX_NAME})",
        "",
    ]
    return "\n".join(lines)


def render_index(entries=None) -> str:
    """``docs/models/README.md``: every card, defaults first."""
    fams = families(entries)
    lines = [GENERATED_NOTE, "", f"# {score_cards().HEADING_TEXT}", "",
             "## spaCR model cards", "",
             "One card per published model. Open **Model Zoo** from the spaCR "
             "home screen to install one, or name its key in a settings file.",
             "", "## Default models", "",
             "| Model | Architecture | Family |", "| --- | --- | --- |"]
    for family in fams:
        entry = family["default"]
        lines.append(f"| {_link(entry)} | {_cell(entry.get('architecture') or '')}"
                     f" | `{family['stem']}` |")
    rest = [(entry, family) for family in fams for entry in family["versions"]
            if family["status"][key_of(entry)] != "default"]
    if rest:
        lines += ["", "## Alternatives and older models", "",
                  "| Model | Status | Architecture |", "| --- | --- | --- |"]
        for entry, family in rest:
            status = STATUS_WORDS[family["status"][key_of(entry)]]
            lines.append(f"| {_link(entry)} | {status} | "
                         f"{_cell(entry.get('architecture') or '')} |")
    return "\n".join(lines) + "\n"


def expected_files(entries=None) -> Dict[str, str]:
    """File name -> contents for everything this tool writes.

    Names are relative to ``docs/models``: the Markdown cards, their index
    and the SVG score cards and grid heading under ``cards/``.
    """
    scores = score_cards()
    out = {INDEX_NAME: render_index(entries)}
    for layout in scores.LAYOUTS:
        out[scores.heading_name(layout)] = scores.render_heading(layout)
    for family in families(entries):
        for entry in family["versions"]:
            key = key_of(entry)
            out[card_file(key)] = render_card(entry, family)
            for layout in scores.LAYOUTS:
                out[scores.card_name(key, layout)] = scores.render_svg(
                    entry, family["status"][key], layout)
    return out


def _written(card_dir: Path) -> List[Path]:
    """Files this tool owns in ``card_dir``: Markdown cards and SVGs."""
    found = list(card_dir.glob("*.md"))
    found += list((card_dir / score_cards().CARD_SUBDIR).glob("*.svg"))
    return sorted(found)


def stale_files(card_dir: Path = CARD_DIR) -> List[str]:
    """Names of cards that are missing, out of date or no longer published.

    A score card's embedded font bytes are left out of the comparison: they
    depend on the fontTools version that subset them, not on the record.
    """
    expected = expected_files()
    same = score_cards().without_font_data
    stale = [name for name, text in expected.items()
             if not (card_dir / name).is_file()
             or same((card_dir / name).read_text(encoding="utf-8"))
             != same(text)]
    if card_dir.is_dir():
        stale += sorted(path.relative_to(card_dir).as_posix()
                        for path in _written(card_dir)
                        if path.relative_to(card_dir).as_posix()
                        not in expected)
    return stale


def write(card_dir: Path = CARD_DIR) -> List[str]:
    """Rewrite every card; remove cards of models no longer published."""
    card_dir.mkdir(parents=True, exist_ok=True)
    expected = expected_files()
    changed = []
    for name, text in expected.items():
        path = card_dir / name
        path.parent.mkdir(parents=True, exist_ok=True)
        if not path.is_file() or path.read_text(encoding="utf-8") != text:
            path.write_text(text, encoding="utf-8")
            changed.append(name)
    for path in _written(card_dir):
        name = path.relative_to(card_dir).as_posix()
        if name not in expected:
            path.unlink()
            changed.append(name)
    return changed


def main(argv: Optional[Sequence[str]] = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true",
                        help="report stale cards and exit 1 instead of writing")
    options = parser.parse_args(argv)
    if options.check:
        stale = stale_files()
        for name in stale:
            print(f"stale: docs/models/{name}")
        return 1 if stale else 0
    for name in write():
        print(f"docs/models/{name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
