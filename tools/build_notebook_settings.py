def _module_from_registry(dotted: str) -> Optional[Any]:
    """Return the CLI module registered for ``dotted``, when available."""
    from spacr.cli import MODULES

    module_name, _, attr = dotted.rpartition(".")
    return next((module for module in MODULES.values()
                 if module.module_name == module_name
                 and module.func_name == attr), None)


def _factory_from_registry(dotted: str) -> Optional[Any]:
    """Return the defaults helper registered for an entry point.

    The CLI registry is shared with the GUI and includes helpers that live
    outside :mod:`spacr.settings`. Reusing it keeps built-in and plugin apps
    consistent without maintaining another entry-point mapping.
    """
    module = _module_from_registry(dotted)
    if module is not None:
        if module.defaults_entry:
            return resolve(module.defaults_entry.replace(":", "."))
        if module.defaults:
            import spacr.settings as settings_module
            return getattr(settings_module, module.defaults, None)
    return None


def _settings_factory(func) -> Optional[Any]:
    """The ``spacr.settings`` helper this function canonicalizes through.

    The fallback for a function the CLI does not register: look for a
    settings helper NAMED IN ITS OWN SOURCE, which is the only definition
    that cannot go out of step with what actually runs. A name-convention
    guess would happily pair a function with a helper it never calls.
    """
    import spacr.settings as settings_module

    candidates = [
        name for name in dir(settings_module)
        if "settings" in name and callable(getattr(settings_module, name, None))
    ]
    try:
        source = inspect.getsource(func)
    except (OSError, TypeError):
        return None
    named = [name for name in candidates if re.search(rf"\b{name}\b", source)]
    if not named:
        return None
    # Longest name wins: `set_default_settings_preprocess_generate_masks`
    # contains no other candidate, but a short generic helper might appear
    # inside a longer one's name.
    named.sort(key=len, reverse=True)
    return getattr(settings_module, named[0])


def _takes_settings_dict(func) -> bool:
    try:
        return "settings" in inspect.signature(func).parameters
    except (TypeError, ValueError):
        return False


def keys_from_factory(factory) -> Dict[str, Any]:
    """Every key the helper declares, by calling it on an empty dict."""
    try:
        result = factory({})
    except Exception:
        return {}
    return dict(result) if isinstance(result, dict) else {}


def keys_from_signature(func) -> Dict[str, Any]:
    """Keyword parameters and their defaults."""
    out: Dict[str, Any] = {}
    try:
        params = inspect.signature(func).parameters
    except (TypeError, ValueError):
        return out
    for name, param in params.items():
        if param.kind in (param.VAR_POSITIONAL, param.VAR_KEYWORD):
            continue
        out[name] = None if param.default is param.empty else param.default
    return out


def keys_from_source(func) -> Dict[str, Any]:
    """Keys the function reads off its ``settings`` argument.

    Walks the AST rather than the text, so a key inside a comment or a
    string is not mistaken for one that is read.
    """
    try:
        source = textwrap.dedent(inspect.getsource(func))
        tree = ast.parse(source)
    except (OSError, TypeError, SyntaxError):
        return {}
    found: Dict[str, Any] = {}
    for node in ast.walk(tree):
        if (isinstance(node, ast.Call)
                and isinstance(node.func, ast.Attribute)
                and node.func.attr in ("get", "setdefault")
                and isinstance(node.func.value, ast.Name)
                and node.func.value.id == "settings"
                and node.args
                and isinstance(node.args[0], ast.Constant)
                and isinstance(node.args[0].value, str)):
            default: Any = None
            if len(node.args) > 1:
                try:
                    default = ast.literal_eval(node.args[1])
                except (ValueError, SyntaxError):
                    default = None
            found.setdefault(node.args[0].value, default)
        elif (isinstance(node, ast.Subscript)
                and isinstance(node.value, ast.Name)
                and node.value.id == "settings"
                and isinstance(node.slice, ast.Constant)
                and isinstance(node.slice.value, str)):
            found.setdefault(node.slice.value, None)
    return found


def surface(func, dotted: str = "") -> Tuple[str, Dict[str, Any]]:
    """``(shape, {key: default})`` for one function.

    :param dotted: the ``spacr.module.function`` path, so the CLI registry
        can be consulted before anything is inferred.
    """
    if _takes_settings_dict(func):
        for factory in (_factory_from_registry(dotted) if dotted else None,
                        _settings_factory(func)):
            if factory is None:
                continue
            keys = keys_from_factory(factory)
            if keys:
                return "factory", keys
        return "source", keys_from_source(func)
    return "signature", keys_from_signature(func)


def notebook_surface(
    func,
    dotted: str,
    *,
    notebook_name: str = "",
) -> Tuple[str, Dict[str, Any]]:
    """Return the editable settings exposed by the corresponding module.

    The mask implementation retains timelapse and motility defaults for old
    settings files, but those controls now belong to dedicated modules. The
    notebooks mirror the current module boundaries rather than exposing
    compatibility-only keys.  The motility notebook deliberately uses the
    timelapse preprocessing function as its first stage, but presents only
    the shared mask settings there; its second stage owns the motility
    controls.  ``notebook_name`` distinguishes that workflow from the
    dedicated Timelapse notebook without changing either public API.
    """
    shape, keys = surface(func, dotted)
    module = _module_from_registry(dotted)
    app_key = getattr(module, "key", "")
    if app_key not in {"mask", "timelapse", "motility"}:
        return shape, keys

    from spacr.settings import (
        categories,
        motility_advanced_settings,
        motility_settings,
        timelapse_settings,
    )

    timelapse_keys = (
        set(timelapse_settings)
        | set(categories["4D Settings (Beta)"])
        | {"timelapse"}
    )
    motility_keys = (set(motility_settings)
                     | set(motility_advanced_settings)
                     | {"motility_analysis"})

    profile = {
        "01_generate_masks.ipynb": "general",
        "01b_generate_timelapse_masks.ipynb": "timelapse",
        "14_motility_assay.ipynb": "motility",
    }.get(notebook_name, app_key)

    if profile == "general" or (profile == "motility" and app_key == "timelapse"):
        hidden = motility_keys | timelapse_keys
        keys = {key: value for key, value in keys.items()
                if key not in hidden}
    elif profile == "timelapse":
        keys = {key: value for key, value in keys.items()
                if key not in motility_keys}
    elif profile == "motility":
        keys = {key: value for key, value in keys.items()
                if key not in timelapse_keys and key != "motility_analysis"}
    return shape, keys


