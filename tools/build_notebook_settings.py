# Rendering
# ---------------------------------------------------------------------------

_DYNAMIC_LITERALS = {
    # These factories deliberately size their worker pool from the current
    # machine.  Committing the evaluated integer makes notebooks alternate
    # between a workstation's 28/30 workers and a hosted runner's 1/2.  Keep
    # the executable expression so the documented default remains truthful
    # and regeneration is independent of the machine doing the check.
    ("spacr.core.preprocess_generate_masks", "n_jobs"):
        "max(1, (__import__('os').cpu_count() or 1) - 4)",
    ("spacr.measure.measure_crop", "n_jobs"):
        "max(1, (__import__('os').cpu_count() or 1) - 2)",
    ("spacr.deep_spacr.deep_spacr", "n_jobs"):
        "max(1, (__import__('os').cpu_count() or 1) - 4)",
}


def _literal(value: Any, *, dotted: str = "", key: str = "") -> str:
    """Repr that round-trips, or a portable executable default expression."""
    dynamic = _DYNAMIC_LITERALS.get((dotted, key))
    if dynamic is not None:
        return dynamic
    if isinstance(value, str):
        resource_root = REPO / "spacr" / "resources"
        try:
            relative = Path(value).resolve().relative_to(resource_root.resolve())
        except (OSError, ValueError):
            pass
        else:
            # ``spacr/resources`` intentionally contains data directories,
            # not import packages.  Python 3.9's ``importlib.resources``
            # fallback can also see ``spec.origin is None`` for an editable
            # installation of the parent package.  Anchor at the package's
            # concrete search path instead; wheels are installed as ordinary
            # directories, so this works in source and installed checkouts on
            # every supported Python.
            resource_parts = ("resources", *relative.parts)
            joined = ", ".join(repr(part) for part in resource_parts)
            # Keep package data portable across source checkouts, wheels and
            # hosted CI instead of baking the developer's absolute path into
            # a committed notebook.
            return (
                "str(__import__('pathlib').Path(next(iter("
                "__import__('spacr').__path__))).joinpath("
                f"{joined}))"
            )
    try:
        if ast.literal_eval(repr(value)) == value:
            return repr(value)
    except (ValueError, SyntaxError, TypeError):
        pass
    return f"None  # {type(value).__name__}, set this yourself"


def setting_name(dotted: str, entries: list) -> str:
    """Return the settings-variable name for one notebook entry."""
    if len(entries) == 1:
        return "settings"
    return f"{dotted.rsplit('.', 1)[1]}_settings"


def api_url(dotted: str) -> str:
    """Return the published API URL for a dotted spaCR callable."""
    module_name = dotted.rpartition(".")[0]
    module_path = module_name.replace(".", "/")
    return f"{API_BASE}/{module_path}/index.html#{dotted}"


def _markdown_text(text: str) -> str:
    """Normalize tooltip prose for a Markdown bullet."""
    return (" ".join(str(text).split())
            .replace("&", "&amp;")
            .replace("<", "&lt;")
            .replace(">", "&gt;"))


def render_help(entries: List[Tuple[str, str, Dict[str, Any], Dict[str, str]]]
                ) -> str:
    """Build the Markdown reference shown above the settings cell."""
    lines = [
        SECTION_TITLE,
        "",
        "Read the descriptions here, then edit only the values in the next "
        "cell. Defaults and descriptions are generated from the installed "
        "spaCR version, so the notebook stays aligned with the API.",
    ]
    for dotted, shape, keys, docs in entries:
        lines.extend([
            "",
            f"### [`{dotted}`]({api_url(dotted)})",
            "",
        ])
        if shape == "source":
            lines.extend([
                "> This function does not yet expose a settings factory. The "
                "list below is recovered from direct settings access in its "
                "source, so a key used only on a dynamic branch may be absent.",
                "",
            ])
        for key in sorted(keys):
            description = _markdown_text(tooltip_for(key, shape, docs))
            if not description:
                description = "No description is available in this version."
            lines.append(f"- **`{key}`** — {description}")
    lines.extend([
        "",
        "## 4. Run",
        "",
        "After editing the settings cell, run the function cell immediately "
        "below it. Long operations report progress through spaCR's logging "
        "system; set `SPACR_LOG_LEVEL=DEBUG` before starting Jupyter for more "
        "detail.",
    ])
    return "\n".join(lines)


def render_cell(entries: List[Tuple[str, str, Dict[str, Any], Dict[str, str]]]
                ) -> str:
    """Build the editable settings-only code cell."""
    lines: List[str] = []
    for index, (dotted, shape, keys, docs) in enumerate(entries):
        name = setting_name(dotted, entries)
        lines.append(f"{name} = {{")
        for key in sorted(keys):
            lines.append(
                f"    {key!r}: {_literal(keys[key], dotted=dotted, key=key)},")
        lines.append("}")
        if index != len(entries) - 1:
            lines.append("")
    return "\n".join(lines)


def _as_source(text: str) -> List[str]:
    """Notebook JSON stores a cell as a list of lines, newlines included."""
    lines = text.split("\n")
    return [line + "\n" for line in lines[:-1]] + [lines[-1]]


# ---------------------------------------------------------------------------
# Rewriting one notebook
# ---------------------------------------------------------------------------

def rebuild(path: Path) -> Optional[str]:
    """Return the notebook's new JSON text, or None when it needs no cell."""
    # Factories are extended by module-level registrations.  Load every
    # registered pipeline before asking any factory for its keys; otherwise
    # the first notebook in a process sees a smaller surface than later ones
    # and pytest's prior imports change the generated result.
    _load_registrations()
    notebook = json.loads(path.read_text())
    entries = []
    for dotted in declared_functions(notebook):
        func = resolve(dotted)
        if func is None:
            continue
        shape, keys = surface(func, dotted)
        if keys:
            entries.append((dotted, shape, keys, param_docs(func)))
    if not entries:
        return None

    help_source = _as_source(render_help(entries))
    cell_source = _as_source(render_cell(entries))
    cells = notebook["cells"]
    retarget_call(cells, entries)

    help_cell = next((cell for cell in cells
                      if _cell_kind(cell) == HELP_CELL_KIND), None)
    if help_cell is None:
        help_cell = next((cell for cell in cells
                          if cell.get("cell_type") == "markdown"
                          and "Every setting this function accepts" in
                          "".join(cell.get("source", []))), None)

    settings_cell = next((cell for cell in cells
                          if _cell_kind(cell) == SETTINGS_CELL_KIND), None)
    if settings_cell is None:
        settings_cell = next((cell for cell in cells
                              if cell.get("cell_type") == "code" and
                              "".join(cell.get("source", [])).startswith(
                                  MARKER)), None)

    if settings_cell is None:
        at = _insertion_point(cells)
        help_cell = _markdown_cell(help_source, HELP_CELL_KIND)
        settings_cell = _code_cell(cell_source, SETTINGS_CELL_KIND)
        cells.insert(at, help_cell)
        cells.insert(at + 1, settings_cell)
    else:
        settings_cell["source"] = cell_source
        settings_cell["outputs"] = []
        settings_cell["execution_count"] = None
        _mark_generated(settings_cell, SETTINGS_CELL_KIND)
        if help_cell is None:
            at = cells.index(settings_cell)
            help_cell = _markdown_cell(help_source, HELP_CELL_KIND)
            cells.insert(at, help_cell)
        else:
            help_cell["source"] = help_source
            _mark_generated(help_cell, HELP_CELL_KIND)

    _remove_legacy_setup(cells, help_cell)
    _place_generated_cells(cells, help_cell, settings_cell)
    _place_run_cell(cells, settings_cell, entries)
    return json.dumps(notebook, indent=1, ensure_ascii=False) + "\n"


def retarget_call(cells: List[dict], entries) -> None:
    """Make a commented example call consume the generated dictionary.

    Some notebooks formerly carried a call such as::

        # custom_volcano_plot(data_path, metadata_path,
        #                     metadata_column='tagm_location', ...)

    which restated the signature separately from the settings cell. Replacing
    it with ``func(**settings)`` ensures renamed parameters fail visibly.

    Only a cell that is ENTIRELY commented-out calls of this function is
    rewritten. A cell with real code in it is somebody's example and is left
    exactly as it is.
    """
    if len(entries) != 1:
        # A notebook running two pipelines names its dicts per function, so
        # there is no single `settings` to hand anything.
        return
    dotted, shape, _keys, _docs = entries[0]
    name = dotted.rsplit(".", 1)[1]
    # A keyword function is spread; a settings-dict function takes the dict.
    call = f"{name}(**settings)" if shape == "signature" else f"{name}(settings)"
    for cell in cells:
        if cell.get("cell_type") != "code":
            continue
        lines = [line.strip() for line in
                 "".join(cell.get("source", [])).split("\n") if line.strip()]
        if not lines:
            continue
        if all(line.startswith(f"# {name}(") for line in lines):
            cell["source"] = _as_source(call)
            cell["outputs"] = []
            cell["execution_count"] = None
            return


def _cell_kind(cell: dict) -> str:
    """Return the spaCR generator kind stored in cell metadata."""
    metadata = cell.get("metadata", {}).get("spacr", {})
    return str(metadata.get("generated", "")) if isinstance(metadata, dict) else ""


def _mark_generated(cell: dict, kind: str) -> None:
    """Mark a cell as generator-owned without adding prose to executable code."""
    cell.setdefault("id", f"spacr-{kind}")
    metadata = cell.setdefault("metadata", {})
    spacr_metadata = metadata.setdefault("spacr", {})
    spacr_metadata.update({
        "generated": kind,
        "tool": "tools/build_notebook_settings.py",
    })


def _code_cell(source: List[str], kind: str = "") -> dict:
    cell = {"cell_type": "code", "execution_count": None, "metadata": {},
            "outputs": [], "source": source}
    if kind:
        _mark_generated(cell, kind)
    return cell


def _markdown_cell(source: List[str], kind: str = "") -> dict:
    cell = {"cell_type": "markdown", "metadata": {}, "source": source}
    if kind:
        _mark_generated(cell, kind)
    return cell


def _remove_legacy_setup(cells: List[dict], help_cell: dict) -> None:
    """Remove the redundant defaults preview that preceded old references."""
    index = next(i for i, cell in enumerate(cells) if cell is help_cell)
    if index and cells[index - 1].get("cell_type") == "code":
        source = "".join(cells[index - 1].get("source", []))
        if "defaults =" in source and "for key in sorted(defaults)" in source:
            cells.pop(index - 1)
            index -= 1
    if index and cells[index - 1].get("cell_type") == "markdown":
        source = "".join(cells[index - 1].get("source", [])).lstrip()
        if source.startswith("## 3. Settings") or source.startswith("## 3. Call it"):
            cells.pop(index - 1)


def _place_generated_cells(cells: List[dict], help_cell: dict,
                           settings_cell: dict) -> None:
    """Place the Markdown reference immediately before editable settings."""
    cells.remove(help_cell)
    cells.remove(settings_cell)
    at = _insertion_point(cells)
    cells.insert(at, help_cell)
    cells.insert(at + 1, settings_cell)


def _place_run_cell(cells: List[dict], settings_cell: dict, entries) -> None:
    """Place the function call immediately after the settings dictionary."""
    names = {dotted.rsplit(".", 1)[1] for dotted, *_rest in entries}
    run_cell = None
    for cell in cells:
        if cell is settings_cell or cell.get("cell_type") != "code":
            continue
        source = "".join(cell.get("source", []))
        if any(re.search(rf"\b{re.escape(name)}\s*\(", source)
               for name in names):
            run_cell = cell
            break
    if run_cell is None:
        return

    # The old standalone Run heading separated settings from the call. Its
    # useful logging guidance now lives at the end of the reference cell.
    for cell in list(cells):
        if cell.get("cell_type") != "markdown":
            continue
        source = "".join(cell.get("source", [])).lstrip()
        if source.startswith("## 4. Run it"):
            cells.remove(cell)

    cells.remove(run_cell)
    at = next(i for i, cell in enumerate(cells) if cell is settings_cell)
    cells.insert(at + 1, run_cell)


def _insertion_point(cells: List[dict]) -> int:
    """Return the position before the run heading or final code cell.

    The settings have to be readable BEFORE the cell that consumes them, or
    a reader who runs the notebook top to bottom meets the run first.
    """
    for index, cell in enumerate(cells):
        source = "".join(cell.get("source", [])).lstrip()
        if cell.get("cell_type") == "markdown" and \
                source.startswith("## 4. Run it"):
            return index
    for index in range(len(cells) - 1, -1, -1):
        if cells[index].get("cell_type") == "code":
            return index
    return len(cells)


# ---------------------------------------------------------------------------
# Entry point
# ---------------------------------------------------------------------------

def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--check", action="store_true",
                        help="do not write; exit 1 if any notebook is stale")
    parser.add_argument("--notebooks", default=str(NOTEBOOKS))
    args = parser.parse_args(argv)

    root = Path(args.notebooks)
    stale, written, skipped = [], [], []
    for path in sorted(root.glob("*.ipynb")):
        try:
            new_text = rebuild(path)
        except Exception as exc:
            print(f"  !! {path.name}: {type(exc).__name__}: {exc}")
            stale.append(path.name)
            continue
        if new_text is None:
            skipped.append(path.name)
            continue
        if new_text == path.read_text():
            continue
        if args.check:
            stale.append(path.name)
        else:
            path.write_text(new_text)
            written.append(path.name)

    if skipped:
        print(f"no settings surface, left alone: {len(skipped)}")
    if args.check:
        if stale:
            print("STALE — re-run tools/build_notebook_settings.py:")
            for name in stale:
                print(f"  {name}")
            return 1
        print("every notebook is current")
        return 0
    print(f"rewrote {len(written)} notebook(s)")
    for name in written:
        print(f"  {name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
