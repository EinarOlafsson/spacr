#!/usr/bin/env python
"""Regenerate the settings reference in every shipped notebook.

Each generated section has three consecutive cells: a readable Markdown
reference, an editable settings dictionary, and the function call that uses
that dictionary. Descriptions come from the live spaCR tooltip table or the
function's scientific-Python docstring; they are never copied into the code
cell. A regeneration test keeps notebooks synchronized with API changes.

Usage::

    python tools/build_notebook_settings.py           # rewrite
    python tools/build_notebook_settings.py --check    # exit 1 if stale

The generator supports three API shapes:

``factory``
    The function takes a settings dict and a ``spacr.settings`` helper
    declares its keys. Keys and defaults come from calling that helper on an
    empty dict; descriptions come from :data:`spacr.settings.tooltips`.

``signature``
    The function takes ordinary keyword arguments -- ``custom_volcano_plot``
    has nine, ``ml_analysis`` twenty-eight. Names and defaults come from
    :func:`inspect.signature` and the tooltip is the function's own
    ``Parameters`` section or ``:param`` field.

``source``
    The function takes a settings dict and NOTHING DECLARES ITS KEYS: it
    reads ``settings.get('x', default)`` inline. The keys are recovered by
    walking the function's AST. The Markdown reference identifies this weaker
    source so readers know that branch-specific keys may be absent.
"""
from __future__ import annotations

import argparse
import ast
import importlib
import inspect
import json
import re
import sys
import textwrap
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple

REPO = Path(__file__).resolve().parent.parent
NOTEBOOKS = REPO / "Notebooks"

# Running ``python tools/build_notebook_settings.py`` otherwise puts only the
# tools directory at the front of sys.path.  In an editable installation that
# can import a different spaCR checkout than the notebooks being regenerated.
# The drift guard imports from this checkout, so the command must do the same.
repo_text = str(REPO)
if sys.path[0] != repo_text:
    sys.path.insert(0, repo_text)

# Freeze the core tooltip table before importing any pipeline. Optional
# dependency availability changes which pipeline modules can register, but it
# must never change the wording of a shared setting in a committed notebook.
# Module-owned keys absent from this snapshot still fall back to the complete
# post-registration table in ``tooltip_for`` below.
from spacr.settings import tooltips as _CORE_TOOLTIP_TABLE  # noqa: E402
CORE_TOOLTIPS = dict(_CORE_TOOLTIP_TABLE)

#: Legacy source marker retained so existing notebooks can be migrated.
MARKER = "# Generated by tools/build_notebook_settings.py — do not edit by hand."

#: Heading of the generated Markdown reference.
SECTION_TITLE = "## 3. Settings and API reference"

#: Metadata values used to find generated cells without putting prose in code.
HELP_CELL_KIND = "settings-help"
SETTINGS_CELL_KIND = "settings"

#: Root of the published sphinx-autoapi tree.
API_BASE = "https://einarolafsson.github.io/spacr/api"


# ---------------------------------------------------------------------------
# Which function a notebook drives
# ---------------------------------------------------------------------------

def declared_functions(notebook: dict) -> List[str]:
    """Return the callable named first in the notebook's function section.

    Related next-step links can name other spaCR callables later in the same
    Markdown cell. The first dotted path is the declared function; treating
    every later link as another pipeline produces unused settings dictionaries.
    """
    for cell in notebook.get("cells", []):
        if cell.get("cell_type") != "markdown":
            continue
        text = "".join(cell.get("source", []))
        if "function" in text and "this notebook runs" in text:
            matches = re.findall(r"`(spacr\.[A-Za-z_0-9.]+)`", text)
            return matches[:1]
    return []


def resolve(dotted: str):
    """Import ``spacr.module.function`` and return the callable, or None."""
    module_name, _, attr = dotted.rpartition(".")
    try:
        return getattr(importlib.import_module(module_name), attr)
    except (ImportError, AttributeError):
        return None


# ---------------------------------------------------------------------------
# The three shapes
# ---------------------------------------------------------------------------

def _factory_from_registry(dotted: str) -> Optional[Any]:
    """Return the defaults helper registered for an entry point.

    The CLI registry is shared with the GUI and includes helpers that live
    outside :mod:`spacr.settings`. Reusing it keeps built-in and plugin apps
    consistent without maintaining another entry-point mapping.
    """
    from spacr.cli import MODULES

    module_name, _, attr = dotted.rpartition(".")
    for module in MODULES.values():
        if module.module_name != module_name or module.func_name != attr:
            continue
        if module.defaults_entry:
            return resolve(module.defaults_entry.replace(":", "."))
        if module.defaults:
            import spacr.settings as settings_module
            return getattr(settings_module, module.defaults, None)
    return None


def _settings_factory(func) -> Optional[Any]:
    """The ``spacr.settings`` helper this function canonicalizes through.

    The fallback for a function the CLI does not register: look for a
    settings helper NAMED IN ITS OWN SOURCE, which is the only definition
    that cannot go out of step with what actually runs. A name-convention
    guess would happily pair a function with a helper it never calls.
    """
    import spacr.settings as settings_module

    candidates = [
        name for name in dir(settings_module)
        if "settings" in name and callable(getattr(settings_module, name, None))
    ]
    try:
        source = inspect.getsource(func)
    except (OSError, TypeError):
        return None
    named = [name for name in candidates if re.search(rf"\b{name}\b", source)]
    if not named:
        return None
    # Longest name wins: `set_default_settings_preprocess_generate_masks`
    # contains no other candidate, but a short generic helper might appear
    # inside a longer one's name.
    named.sort(key=len, reverse=True)
    return getattr(settings_module, named[0])


def _takes_settings_dict(func) -> bool:
    try:
        return "settings" in inspect.signature(func).parameters
    except (TypeError, ValueError):
        return False


def keys_from_factory(factory) -> Dict[str, Any]:
    """Every key the helper declares, by calling it on an empty dict."""
    try:
        result = factory({})
    except Exception:
        return {}
    return dict(result) if isinstance(result, dict) else {}


def keys_from_signature(func) -> Dict[str, Any]:
    """Keyword parameters and their defaults."""
    out: Dict[str, Any] = {}
    try:
        params = inspect.signature(func).parameters
    except (TypeError, ValueError):
        return out
    for name, param in params.items():
        if param.kind in (param.VAR_POSITIONAL, param.VAR_KEYWORD):
            continue
        out[name] = None if param.default is param.empty else param.default
    return out


def keys_from_source(func) -> Dict[str, Any]:
    """Keys the function reads off its ``settings`` argument.

    Walks the AST rather than the text, so a key inside a comment or a
    string is not mistaken for one that is read.
    """
    try:
        source = textwrap.dedent(inspect.getsource(func))
        tree = ast.parse(source)
    except (OSError, TypeError, SyntaxError):
        return {}
    found: Dict[str, Any] = {}
    for node in ast.walk(tree):
        if (isinstance(node, ast.Call)
                and isinstance(node.func, ast.Attribute)
                and node.func.attr in ("get", "setdefault")
                and isinstance(node.func.value, ast.Name)
                and node.func.value.id == "settings"
                and node.args
                and isinstance(node.args[0], ast.Constant)
                and isinstance(node.args[0].value, str)):
            default: Any = None
            if len(node.args) > 1:
                try:
                    default = ast.literal_eval(node.args[1])
                except (ValueError, SyntaxError):
                    default = None
            found.setdefault(node.args[0].value, default)
        elif (isinstance(node, ast.Subscript)
                and isinstance(node.value, ast.Name)
                and node.value.id == "settings"
                and isinstance(node.slice, ast.Constant)
                and isinstance(node.slice.value, str)):
            found.setdefault(node.slice.value, None)
    return found


def surface(func, dotted: str = "") -> Tuple[str, Dict[str, Any]]:
    """``(shape, {key: default})`` for one function.

    :param dotted: the ``spacr.module.function`` path, so the CLI registry
        can be consulted before anything is inferred.
    """
    if _takes_settings_dict(func):
        for factory in (_factory_from_registry(dotted) if dotted else None,
                        _settings_factory(func)):
            if factory is None:
                continue
            keys = keys_from_factory(factory)
            if keys:
                return "factory", keys
        return "source", keys_from_source(func)
    return "signature", keys_from_signature(func)


# ---------------------------------------------------------------------------
# Tooltips, always read now and never pasted
# ---------------------------------------------------------------------------

def param_docs(func) -> Dict[str, str]:
    """Return parameter descriptions from RST or numpydoc docstrings."""
    doc = inspect.getdoc(func) or ""
    out: Dict[str, str] = {}
    for match in re.finditer(
            r"^:param\s+(\w+):\s*(.+?)(?=^\s*:(?:param|returns|raises|rtype)\b|\Z)",
            doc, re.S | re.M):
        out[match.group(1)] = " ".join(match.group(2).split())

    # Scientific-Python APIs use a ``Parameters`` section rather than RST
    # fields.  Stop at the next underlined section heading so Returns/Raises
    # entries cannot be mistaken for parameters.
    lines = doc.splitlines()
    section = next((
        index for index in range(len(lines) - 1)
        if lines[index].strip() == "Parameters"
        and set(lines[index + 1].strip()) == {"-"}
    ), None)
    if section is None:
        return out

    parameter = re.compile(
        r"^([A-Za-z_]\w*(?:\s*,\s*[A-Za-z_]\w*)*)\s*:\s*.+$"
    )
    index = section + 2
    while index < len(lines):
        if (index + 1 < len(lines) and lines[index].strip()
                and set(lines[index + 1].strip()) == {"-"}):
            break
        match = parameter.match(lines[index].strip())
        if match is None:
            index += 1
            continue
        names = [name.strip() for name in match.group(1).split(",")]
        index += 1
        description = []
        while index < len(lines):
            if (index + 1 < len(lines) and lines[index].strip()
                    and set(lines[index + 1].strip()) == {"-"}):
                break
            if parameter.match(lines[index].strip()):
                break
            if lines[index].strip():
                description.append(lines[index].strip())
            index += 1
        rendered = " ".join(description)
        for name in names:
            out.setdefault(name, rendered)
    return out


_REGISTERED = False


def _load_registrations() -> None:
    """Import every pipeline module, so its registered tooltips exist.

    ``spacr.settings.tooltips`` is not complete on import. Six pipelines --
    ``barcode_qc``, ``illumination``, ``convert`` and the rest -- own their
    keys and merge them in from their own module via
    :func:`spacr.settings.register_defaults`, which only runs when that
    module is imported. Read the dict cold and ``dst`` and ``cmap`` look
    undocumented; they are documented by whoever owns them.

    Getting this wrong is not a missing sentence, it is a WRONG one: the
    generator would have written "no description" into a notebook for a key
    that has a perfectly good one.
    """
    global _REGISTERED
    if _REGISTERED:
        return
    from spacr.cli import MODULES
    for module in MODULES.values():
        try:
            importlib.import_module(module.module_name)
        except Exception:
            # A pipeline whose optional dependency is absent still leaves
            # every other pipeline's tooltips loaded.
            pass
    _REGISTERED = True


def tooltip_for(key: str, shape: str, docs: Dict[str, str]) -> str:
    """One sentence describing ``key``, from whichever source declares it."""
    if shape == "signature":
        return docs.get(key, "")
    if key in CORE_TOOLTIPS:
        return str(CORE_TOOLTIPS[key] or docs.get(key, ""))
    _load_registrations()
    from spacr.settings import tooltips
    return str(tooltips.get(key, "") or docs.get(key, ""))


