def rebuild(path: Path) -> Optional[str]:
    """Return the notebook's new JSON text, or None when it needs no cell."""
    # Factories are extended by module-level registrations.  Load every
    # registered pipeline before asking any factory for its keys; otherwise
    # the first notebook in a process sees a smaller surface than later ones
    # and pytest's prior imports change the generated result.
    _load_registrations()
    notebook = json.loads(path.read_text())
    entries = []
    for dotted in declared_functions(notebook):
        func = resolve(dotted)
        if func is None:
            continue
        shape, keys = notebook_surface(
            func, dotted, notebook_name=path.name
        )
        if keys:
            entries.append((dotted, shape, keys, param_docs(func)))
    if not entries:
        return None

    _refresh_notebook_prose(path, notebook, entries)

    help_source = _as_source(render_help(entries))
    rendered_settings = [
        (kind, _as_source(source))
        for kind, source in render_settings_cells(entries)
    ]
    cells = notebook["cells"]
    retarget_call(cells, entries)

    help_cell = next((cell for cell in cells
                      if _cell_kind(cell) == HELP_CELL_KIND), None)
    if help_cell is None:
        help_cell = next((cell for cell in cells
                          if cell.get("cell_type") == "markdown"
                          and "Every setting this function accepts" in
                          "".join(cell.get("source", []))), None)

    settings_cells = {
        kind: next((cell for cell in cells if _cell_kind(cell) == kind), None)
        for kind, _source in rendered_settings
    }
    if settings_cells[SETTINGS_CELL_KIND] is None:
        settings_cells[SETTINGS_CELL_KIND] = next((
            cell for cell in cells
            if cell.get("cell_type") == "code"
            and "".join(cell.get("source", [])).startswith(MARKER)
        ), None)

    if settings_cells[SETTINGS_CELL_KIND] is None:
        at = _insertion_point(cells)
        help_cell = _markdown_cell(help_source, HELP_CELL_KIND)
        cells.insert(at, help_cell)
        for offset, (kind, source) in enumerate(rendered_settings, 1):
            settings_cells[kind] = _code_cell(source, kind)
            cells.insert(at + offset, settings_cells[kind])
    else:
        for kind, source in rendered_settings:
            settings_cell = settings_cells.get(kind)
            if settings_cell is None:
                settings_cell = _code_cell(source, kind)
                settings_cells[kind] = settings_cell
                cells.insert(cells.index(settings_cells[SETTINGS_CELL_KIND]) + 1,
                             settings_cell)
            else:
                settings_cell["source"] = source
                settings_cell["outputs"] = []
                settings_cell["execution_count"] = None
                _mark_generated(settings_cell, kind)
        if help_cell is None:
            at = cells.index(settings_cells[SETTINGS_CELL_KIND])
            help_cell = _markdown_cell(help_source, HELP_CELL_KIND)
            cells.insert(at, help_cell)
        else:
            help_cell["source"] = help_source
            _mark_generated(help_cell, HELP_CELL_KIND)

    # Remove a formerly generated organelle cell when a function no longer
    # exposes organelle settings.
    live_kinds = {kind for kind, _source in rendered_settings}
    for cell in list(cells):
        if (_cell_kind(cell) == ORGANELLE_CELL_KIND
                and ORGANELLE_CELL_KIND not in live_kinds):
            cells.remove(cell)

    _remove_legacy_setup(cells, help_cell)
    ordered_settings = [settings_cells[kind]
                        for kind, _source in rendered_settings]
    _place_generated_cells(cells, help_cell, ordered_settings)
    _place_run_cell(cells, ordered_settings[-1], entries)
    return json.dumps(notebook, indent=1, ensure_ascii=False) + "\n"


def retarget_call(cells: List[dict], entries) -> None:
    """Make a commented example call consume the generated dictionary.

    Some notebooks formerly carried a call such as::

        # custom_volcano_plot(data_path, metadata_path,
        #                     metadata_column='tagm_location', ...)

    which restated the signature separately from the settings cell. Replacing
    it with ``func(**settings)`` ensures renamed parameters fail visibly.

    Only a cell that is ENTIRELY commented-out calls of this function is
    rewritten. A cell with real code in it is somebody's example and is left
    exactly as it is.
    """
    if len(entries) != 1:
        # A notebook running two pipelines names its dicts per function, so
        # there is no single `settings` to hand anything.
        return
    dotted, shape, _keys, _docs = entries[0]
    name = dotted.rsplit(".", 1)[1]
    # A keyword function is spread; a settings-dict function takes the dict.
    call = f"{name}(**settings)" if shape == "signature" else f"{name}(settings)"
    for cell in cells:
        if cell.get("cell_type") != "code":
            continue
        lines = [line.strip() for line in
                 "".join(cell.get("source", [])).split("\n") if line.strip()]
        if not lines:
            continue
        if all(line.startswith(f"# {name}(") for line in lines):
            cell["source"] = _as_source(call)
            cell["outputs"] = []
            cell["execution_count"] = None
            return


def _cell_kind(cell: dict) -> str:
    """Return the spaCR generator kind stored in cell metadata."""
    metadata = cell.get("metadata", {}).get("spacr", {})
    return str(metadata.get("generated", "")) if isinstance(metadata, dict) else ""


def _mark_generated(cell: dict, kind: str) -> None:
    """Mark a cell as generator-owned without adding prose to executable code."""
    cell.setdefault("id", f"spacr-{kind}")
    metadata = cell.setdefault("metadata", {})
    spacr_metadata = metadata.setdefault("spacr", {})
    spacr_metadata.update({
        "generated": kind,
        "tool": "tools/build_notebook_settings.py",
    })


def _code_cell(source: List[str], kind: str = "") -> dict:
    cell = {"cell_type": "code", "execution_count": None, "metadata": {},
            "outputs": [], "source": source}
    if kind:
        _mark_generated(cell, kind)
    return cell


def _markdown_cell(source: List[str], kind: str = "") -> dict:
    cell = {"cell_type": "markdown", "metadata": {}, "source": source}
    if kind:
        _mark_generated(cell, kind)
    return cell


def _remove_legacy_setup(cells: List[dict], help_cell: dict) -> None:
    """Remove the redundant defaults preview that preceded old references."""
    index = next(i for i, cell in enumerate(cells) if cell is help_cell)
    if index and cells[index - 1].get("cell_type") == "code":
        source = "".join(cells[index - 1].get("source", []))
        if "defaults =" in source and "for key in sorted(defaults)" in source:
            cells.pop(index - 1)
            index -= 1
    if index and cells[index - 1].get("cell_type") == "markdown":
        source = "".join(cells[index - 1].get("source", [])).lstrip()
        if source.startswith("## 3. Settings") or source.startswith("## 3. Call it"):
            cells.pop(index - 1)


def _place_generated_cells(cells: List[dict], help_cell: dict,
                           settings_cells: List[dict]) -> None:
    """Place the Markdown reference immediately before editable settings."""
    cells.remove(help_cell)
    for settings_cell in settings_cells:
        cells.remove(settings_cell)
    at = _insertion_point(cells)
    cells.insert(at, help_cell)
    for offset, settings_cell in enumerate(settings_cells, 1):
        cells.insert(at + offset, settings_cell)


def _place_run_cell(cells: List[dict], settings_cell: dict, entries) -> None:
    """Place the function call immediately after the settings dictionary."""
    names = {dotted.rsplit(".", 1)[1] for dotted, *_rest in entries}
    run_cell = None
    for cell in cells:
        if cell is settings_cell or cell.get("cell_type") != "code":
            continue
        source = "".join(cell.get("source", []))
        if any(re.search(rf"\b{re.escape(name)}\s*\(", source)
               for name in names):
            run_cell = cell
            break
    if run_cell is None:
        return

    # The old standalone Run heading separated settings from the call. Its
    # useful logging guidance now lives at the end of the reference cell.
    for cell in list(cells):
        if cell.get("cell_type") != "markdown":
            continue
        source = "".join(cell.get("source", [])).lstrip()
        if source.startswith("## 4. Run it"):
            cells.remove(cell)

    cells.remove(run_cell)
    at = next(i for i, cell in enumerate(cells) if cell is settings_cell)
    cells.insert(at + 1, run_cell)


def _insertion_point(cells: List[dict]) -> int:
    """Return the position before the run heading or final code cell.

    The settings have to be readable BEFORE the cell that consumes them, or
    a reader who runs the notebook top to bottom meets the run first.
    """
    for index, cell in enumerate(cells):
        source = "".join(cell.get("source", [])).lstrip()
        if cell.get("cell_type") == "markdown" and \
                source.startswith("## 4. Run it"):
            return index
    for index in range(len(cells) - 1, -1, -1):
        if cells[index].get("cell_type") == "code":
            return index
    return len(cells)


