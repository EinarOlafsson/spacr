def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--check", action="store_true",
                        help="do not write; exit 1 if any notebook is stale")
    parser.add_argument("--notebooks", default=str(NOTEBOOKS))
    args = parser.parse_args(argv)

    root = Path(args.notebooks)
    stale, written, skipped = [], [], []
    for path in sorted(root.glob("*.ipynb")):
        try:
            new_text = rebuild(path)
        except Exception as exc:
            print(f"  !! {path.name}: {type(exc).__name__}: {exc}")
            stale.append(path.name)
            continue
        if new_text is None:
            skipped.append(path.name)
            continue
        if new_text == path.read_text():
            continue
        if args.check:
            stale.append(path.name)
        else:
            path.write_text(new_text)
            written.append(path.name)

    if skipped:
        print(f"no settings surface, left alone: {len(skipped)}")
    if args.check:
        if stale:
            print("STALE — re-run tools/build_notebook_settings.py:")
            for name in stale:
                print(f"  {name}")
            return 1
        print("every notebook is current")
        return 0
    print(f"rewrote {len(written)} notebook(s)")
    for name in written:
        print(f"  {name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
