"""Reviewed translations for context-sensitive spaCR interface text.

Machine-translation models receive too little context from a one- or two-word
button caption or a dense scientific introduction without application
context.  Several grammatically valid translations consequently used
the wrong sense: a microplate *well* became an interjection, a scientific
*figure* became a number, an image *crop* became agriculture, and a parameter
*sweep* became cleaning.  This module is the small human-reviewed vocabulary
layer for those high-risk captions.

The catalog builder consumes :data:`REVIEWED_UI_TRANSLATIONS` before any
generated-catalog or model cache.  Every row is intentionally complete for all
nine non-English runtime languages.  Product names, file formats, identifiers,
and algorithm names belong to the separate exact-identity contract in
``build_i18n_catalogs.py``.
"""

